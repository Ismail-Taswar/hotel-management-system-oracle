==================Booking_view===================

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "BOOKING_VIEW" ("BOOKING_M_ID", "BOOKING_ID", "BOOKING_M_DATE", "FIRST_NAME", "LAST_NAME", "GUEST_ID", "TOTAL_AMOUNT", "DISCOUNT", "GRANT_TOTAL", "ADVANCED_PAID", "DUE", "PAYMENT_STATUS", "NUMBER_OF_ADULT", "NUMBER_OF_CHILDREN", "CHECK_IN_DATE", "CHECK_OUT_DATE", "PAYMENT_MODE_ID", "PAYMENT_MODE_NAME", "ACTION_USER", "ACTION_DATE_TIME", "BOOKING_D_ID", "ROOM_ID", "ROOM_NUMBER", "ROOM_RENT", "ROOM_TYPE_ID", "ROOM_TYPE_NAME", "TOTAL_BOOKED_DAYS") AS 
  select  BOOKING_D.BOOKING_M_ID,BOOKING_M.BOOKING_ID,BOOKING_M.BOOKING_M_DATE,GUEST.FIRST_NAME,
        GUEST.LAST_NAME,BOOKING_M.GUEST_ID,BOOKING_M.TOTAL_AMOUNT,BOOKING_M.DISCOUNT,BOOKING_M.GRANT_TOTAL,
        BOOKING_M.ADVANCED_PAID,BOOKING_M.DUE,BOOKING_M.PAYMENT_STATUS,
        BOOKING_M.NUMBER_OF_ADULT,BOOKING_M.NUMBER_OF_CHILDREN,BOOKING_M.CHECK_IN_DATE,BOOKING_M.CHECK_OUT_DATE,
        BOOKING_M.PAYMENT_MODE_ID,PAYMENT_MODE.PAYMENT_MODE_NAME,BOOKING_M.ACTION_USER, BOOKING_M.ACTION_DATE_TIME,
        BOOKING_D.BOOKING_D_ID,BOOKING_D.ROOM_ID,ROOM.ROOM_NUMBER,ROOM.ROOM_RENT,ROOM.ROOM_TYPE_ID, ROOM_TYPE_NAME,TOTAL_BOOKED_DAYS
from    BOOKING_D,BOOKING_M,GUEST,ROOM,PAYMENT_MODE,ROOM_TYPE
where   BOOKING_D.BOOKING_M_ID = BOOKING_M.BOOKING_M_ID
--and     BOOKING_D2.BOOKING_M_ID = BOOKING_M.BOOKING_M_ID(+)
and     BOOKING_M.GUEST_ID = GUEST.GUEST_ID(+)
and     BOOKING_D.ROOM_ID = ROOM.ROOM_ID(+)
and     BOOKING_M.PAYMENT_MODE_ID = PAYMENT_MODE.PAYMENT_MODE_ID(+)
and     ROOM.ROOM_TYPE_ID = ROOM_TYPE.ROOM_TYPE_ID(+)
order   by BOOKING_M.BOOKING_ID;


=====================FOOD_VIEW====================

    CREATE OR REPLACE FORCE EDITIONABLE VIEW "FOOD_VIEW" ("FOOD_D_ID", "FOOD_M_ID", "FOOD_ID", "FOOD_QUANTITY", "FOOD_RATE", "TOTAL_AMOUNT", "BOOKING_M_ID", "INVOICE_NUMBER", "ORDER_DATE", "ACTION_USER", "ACTION_DATE_TIME", "BOOKING_ID", "GUEST_ID", "GUEST_NAME", "FOOD_TYPE_ID", "FOOD_TYPE_NAME", "FOOD_CATEGORY_ID", "FOOD_CATEGORY_NAME", "FOOD_NAME") AS 
  SELECT FOOD_D.FOOD_D_ID, FOOD_D.FOOD_M_ID,FOOD_D.FOOD_ID,FOOD_D.FOOD_QUANTITY,FOOD_D.FOOD_RATE,FOOD_D.TOTAL_AMOUNT,
       FOOD_M.BOOKING_M_ID,FOOD_M.INVOICE_NUMBER,FOOD_M.ORDER_DATE,FOOD_M.ACTION_USER,FOOD_M.ACTION_DATE_TIME,
      BOOKING_M.BOOKING_ID,BOOKING_M.GUEST_ID,FIRST_NAME||' '||LAST_NAME GUEST_NAME,
      FOOD_TYPE.FOOD_TYPE_ID,FOOD_TYPE.FOOD_TYPE_NAME,
      FOOD_CATEGORY.FOOD_CATEGORY_ID,FOOD_CATEGORY.FOOD_CATEGORY_NAME,
      FOOD.FOOD_NAME
FROM   FOOD_TYPE,FOOD_M,FOOD_D,FOOD_CATEGORY,FOOD,GUEST,BOOKING_M
WHERE  FOOD_D.FOOD_M_ID = FOOD_M.FOOD_M_ID
AND    FOOD_D.FOOD_ID = FOOD.FOOD_ID(+)
AND    FOOD_M.BOOKING_M_ID = BOOKING_M.BOOKING_M_ID(+)
AND    FOOD.FOOD_CATEGORY_ID = FOOD_CATEGORY.FOOD_CATEGORY_ID(+)
AND    FOOD.FOOD_TYPE_ID = FOOD_TYPE.FOOD_TYPE_ID(+)
AND    BOOKING_M.GUEST_ID = GUEST.GUEST_ID(+)
ORDER  BY  FOOD_D.FOOD_M_ID;

=====================SERVICE_VIEW====================

CREATE OR REPLACE FORCE EDITIONABLE VIEW "SERVICE_VIEW" ("SERVICE_M_ID", "BOOKING_M_ID", "INVOICE_NUMBER", "SERVICE_DATE", "ACTION_USER", "ACTION_DATE_TIME", "SERVICE_D_ID", "SERVICE_ID", "SERVICE_DURATION", "SERVICE_RATE", "GUEST_ID", "BOOKING_ID", "SERVICE_NAME", "GUEST_NAME", "TOTAL_AMOUNT") AS 
  select SERVICE_D.SERVICE_M_ID, SERVICE_M.BOOKING_M_ID, INVOICE_NUMBER, SERVICE_DATE,
       SERVICE_M.ACTION_USER, SERVICE_M.ACTION_DATE_TIME,
       SERVICE_D_ID, SERVICE_D.SERVICE_ID, SERVICE_DURATION, SERVICE.SERVICE_RATE,
       BOOKING_M.GUEST_ID,BOOKING_ID,SERVICE_NAME,FIRST_NAME||' '||LAST_NAME GUEST_NAME,service_d.TOTAL_AMOUNT
from   SERVICE_M,SERVICE_D,SERVICE,BOOKING_M,GUEST
where  SERVICE_D.SERVICE_M_ID = SERVICE_M.SERVICE_M_ID
and    SERVICE_D.SERVICE_ID = SERVICE.SERVICE_ID
and    SERVICE_M.BOOKING_M_ID = BOOKING_M.BOOKING_M_ID
and    BOOKING_M.GUEST_ID = GUEST.GUEST_ID
order  by SERVICE_D.SERVICE_M_ID;


============Bill_view===============

CREATE OR REPLACE  VIEW BILL_VIEW_apex
as
select  booking_m_id,Guest_Name,GUEST_ID,booking_id,due,sum(TOTAL_AMOUNT) food_bill
from (
select distinct b.booking_m_id,b.GUEST_ID,b.FIRST_NAME||' '||b.LAST_NAME Guest_Name, b.booking_id, b.due, f.TOTAL_AMOUNT
from   Booking_view b , FOOD_VIEW f
where f.booking_m_id = b.booking_m_id
)
group by booking_m_id,GUEST_ID,Guest_Name,booking_id,due;


